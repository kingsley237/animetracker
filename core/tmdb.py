"""
Kinema data source - TMDB (The Movie Database) client for TV shows & movies.

Credentials, in order of precedence:
  1. A token the user pasted in Settings ("tmdb_token_override")
  2. The token embedded into release builds (core/_embedded_secrets.py,
     generated by build_exe.py, never committed)
  3. secrets.local.json at the repo root (development, never committed)

This product uses the TMDB API but is not endorsed or certified by TMDB.
Streaming availability ("where to watch") is provided by JustWatch.
"""
from __future__ import annotations

import json
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Tuple

import requests

API = "https://api.themoviedb.org/3"
IMG = "https://image.tmdb.org/t/p"
DEFAULT_REGION = "US"
DEFAULT_LANGUAGE = "en-US"

_ROOT = Path(__file__).resolve().parents[1]
_session: Optional[requests.Session] = None
_session_lock = threading.Lock()
_cache: Dict[str, Tuple[float, Any]] = {}
_cache_lock = threading.Lock()
CACHE_TTL = 15 * 60          # seconds; details change rarely within a session


# ── credentials & settings ────────────────────────────────────────────────────

def _settings_value(key: str, default: str = "") -> str:
    try:
        from core.app_settings import app_settings
        return str(app_settings().value(key, default) or default).strip()
    except Exception:
        return default


def get_credentials() -> Dict[str, str]:
    """{'token': ..., 'api_key': ..., 'source': 'settings'|'embedded'|'local'|''}"""
    override = _settings_value("tmdb_token_override")
    if override:
        # A pasted v4 read token is long and dotted; a v3 key is 32 hex chars.
        if "." in override and len(override) > 60:
            return {"token": override, "api_key": "", "source": "settings"}
        return {"token": "", "api_key": override, "source": "settings"}
    try:
        from core import _embedded_secrets as emb  # type: ignore
        if getattr(emb, "TMDB_READ_TOKEN", "") or getattr(emb, "TMDB_API_KEY", ""):
            return {"token": getattr(emb, "TMDB_READ_TOKEN", ""),
                    "api_key": getattr(emb, "TMDB_API_KEY", ""), "source": "embedded"}
    except Exception:
        pass
    local = _ROOT / "secrets.local.json"
    if local.exists():
        try:
            d = json.loads(local.read_text(encoding="utf-8"))
            if d.get("tmdb_read_token") or d.get("tmdb_api_key"):
                return {"token": d.get("tmdb_read_token", ""),
                        "api_key": d.get("tmdb_api_key", ""), "source": "local"}
        except Exception:
            pass
    return {"token": "", "api_key": "", "source": ""}


def has_credentials() -> bool:
    c = get_credentials()
    return bool(c["token"] or c["api_key"])


def region() -> str:
    return (_settings_value("tmdb_region", DEFAULT_REGION) or DEFAULT_REGION).upper()


def image_url(path: Optional[str], size: str = "w500") -> str:
    """TMDB image path -> full URL. Sizes: w92..w780, original."""
    return f"{IMG}/{size}{path}" if path else ""


# ── HTTP core ─────────────────────────────────────────────────────────────────

def _get_session() -> requests.Session:
    global _session
    with _session_lock:
        if _session is None:
            s = requests.Session()
            s.headers.update({"Accept": "application/json", "User-Agent": "Raiko-Kinema"})
            _session = s
        return _session


def clear_cache():
    with _cache_lock:
        _cache.clear()


def get(path: str, params: Optional[Dict[str, Any]] = None, ttl: int = CACHE_TTL,
        retries: int = 2) -> Optional[Dict]:
    """GET /3{path}. Returns parsed JSON, or None when offline / no key /
    not found. Never raises - callers treat None as 'unknown'."""
    creds = get_credentials()
    if not (creds["token"] or creds["api_key"]):
        return None
    params = dict(params or {})
    params.setdefault("language", DEFAULT_LANGUAGE)
    headers = {}
    if creds["token"]:
        headers["Authorization"] = f"Bearer {creds['token']}"
    else:
        params["api_key"] = creds["api_key"]
    key = path + "?" + "&".join(f"{k}={params[k]}" for k in sorted(params) if k != "api_key")
    if ttl:
        with _cache_lock:
            hit = _cache.get(key)
        if hit and time.time() - hit[0] < ttl:
            return hit[1]
    for attempt in range(retries + 1):
        try:
            r = _get_session().request("GET", API + path, params=params,
                                       headers=headers, timeout=15)
            if r.status_code == 429:
                time.sleep(min(int(r.headers.get("Retry-After", "2") or 2), 10))
                continue
            if r.status_code == 404:
                return None
            r.raise_for_status()
            data = r.json()
            if ttl:
                with _cache_lock:
                    _cache[key] = (time.time(), data)
            return data
        except requests.HTTPError:
            return None
        except Exception:
            if attempt < retries:
                time.sleep(0.6 * (attempt + 1))
    return None


def get_many(requests_: Iterable[Tuple[str, Optional[Dict[str, Any]]]],
             workers: int = 6) -> List[Optional[Dict]]:
    """Run several GETs in parallel (TMDB calls are slow per-request but
    not rate-limited hard), preserving order."""
    items = list(requests_)
    if not items:
        return []
    with ThreadPoolExecutor(max_workers=min(workers, len(items))) as pool:
        return list(pool.map(lambda pr: get(pr[0], pr[1]), items))


# ── endpoints ─────────────────────────────────────────────────────────────────

def search(query: str, kind: str = "multi", page: int = 1) -> List[Dict]:
    """kind: 'multi' | 'tv' | 'movie'. Multi results are filtered to tv/movie."""
    data = get(f"/search/{kind}", {"query": query, "page": page, "include_adult": "false"}, ttl=300)
    results = (data or {}).get("results") or []
    if kind == "multi":
        results = [r for r in results if r.get("media_type") in ("tv", "movie")]
    else:
        for r in results:
            r.setdefault("media_type", kind)
    return results


def tv_details(tv_id: int) -> Optional[Dict]:
    return get(f"/tv/{int(tv_id)}", {
        "append_to_response": "videos,credits,watch/providers,external_ids,content_ratings",
        "include_video_language": "en,null"})


def tv_season(tv_id: int, season_number: int) -> Optional[Dict]:
    return get(f"/tv/{int(tv_id)}/season/{int(season_number)}")


def movie_details(movie_id: int) -> Optional[Dict]:
    return get(f"/movie/{int(movie_id)}", {
        "append_to_response": "videos,credits,release_dates,watch/providers,external_ids",
        "include_video_language": "en,null"})


def collection(collection_id: int) -> Optional[Dict]:
    return get(f"/collection/{int(collection_id)}")


def trending(kind: str = "all", window: str = "week", page: int = 1) -> List[Dict]:
    data = get(f"/trending/{kind}/{window}", {"page": page}, ttl=1800)
    return [r for r in ((data or {}).get("results") or []) if r.get("media_type", kind) in ("tv", "movie")]


def popular(kind: str, page: int = 1) -> List[Dict]:
    data = get(f"/{kind}/popular", {"page": page}, ttl=1800)
    res = (data or {}).get("results") or []
    for r in res:
        r.setdefault("media_type", kind)
    return res


# ── helpers used by providers ─────────────────────────────────────────────────

def watch_providers(details: Dict, country: Optional[str] = None) -> Dict[str, List[str]]:
    """{'stream': [...], 'rent': [...], 'buy': [...], 'link': url} for a country."""
    country = (country or region()).upper()
    res = ((details or {}).get("watch/providers") or {}).get("results", {}).get(country) or {}
    names = lambda key: [p.get("provider_name") for p in res.get(key) or [] if p.get("provider_name")]
    return {"stream": names("flatrate") + [n for n in names("free") if n not in names("flatrate")],
            "rent": names("rent"), "buy": names("buy"), "link": res.get("link", "")}


def videos(details: Dict) -> List[Dict]:
    """Trailers first, then teasers/clips; YouTube only. Same shape as
    core.videos playlists: {id, site, kind, title, thumb}."""
    order = {"Trailer": 0, "Teaser": 1, "Clip": 2, "Featurette": 3, "Behind the Scenes": 4}
    vids = [v for v in ((details or {}).get("videos") or {}).get("results") or []
            if (v.get("site") or "").lower() == "youtube" and v.get("key")]
    vids.sort(key=lambda v: (order.get(v.get("type"), 9), not v.get("official"),
                             v.get("published_at") or ""), reverse=False)
    out = []
    for v in vids:
        kind = "promo" if v.get("type") in ("Trailer", "Teaser") else "clip"
        out.append({"id": v["key"], "site": "youtube", "kind": kind,
                    "title": v.get("name") or v.get("type") or "Video",
                    "thumb": f"https://i.ytimg.com/vi/{v['key']}/hqdefault.jpg"})
    return out


def us_release_dates(details: Dict, country: Optional[str] = None) -> Dict[str, str]:
    """Movie release dates for a country by type: theatrical / digital / physical."""
    country = (country or region()).upper()
    types = {1: "premiere", 2: "theatrical_limited", 3: "theatrical", 4: "digital", 5: "physical", 6: "tv"}
    out: Dict[str, str] = {}
    for c in ((details or {}).get("release_dates") or {}).get("results") or []:
        if c.get("iso_3166_1") != country:
            continue
        for rd in c.get("release_dates") or []:
            t = types.get(rd.get("type"))
            d = (rd.get("release_date") or "")[:10]
            if t and d and (t not in out or d < out[t]):
                out[t] = d
    return out
